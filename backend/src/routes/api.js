const {Router}=require('express');
const contactos=require('../controllers/contactos');
const publicaciones=require('../controllers/publicaciones');
const encuestas=require('../controllers/encuestas');
const admin=require('../controllers/admin');
const {adminSeguro}=require('../middleware/admin');
module.exports=db=>{
  const router=Router(),c=contactos(db),p=publicaciones(db),e=encuestas(db);
  router.get('/categorias',p.categorias);
  router.get('/categorias/:id',p.categoriaDetalle);
  router.get('/publicaciones',p.publicaciones);
  router.get('/publicaciones/:id',p.publicacionDetalle);
  router.post('/solicitudes-publicacion',p.crearSolicitud);
  router.get('/solicitudes-publicacion/mias',p.misSolicitudes);
  router.get('/solicitudes-publicacion/:id',p.miSolicitudDetalle);
  router.post('/solicitudes-contacto',p.crearContacto);
  router.get('/solicitudes-contacto/mias',p.misContactos);
  router.get('/solicitudes-contacto/:id',p.miContactoDetalle);
  router.post('/contactos',c.crear);
  router.get('/contactos/mi',c.mi);
  router.put('/contactos/mi',c.actualizar);
  router.get('/encuestas',e.listar);
  router.get('/encuestas/:id',e.detalle);
  router.post('/encuestas/:id/respuestas',e.responder);
  router.use('/admin',adminSeguro);
  router.get('/admin/solicitudes-publicacion',admin.solicitudes);
  router.get('/admin/solicitudes-publicacion/:id',admin.solicitudDetalle);
  router.get('/admin/solicitudes-contacto',admin.solicitudesContacto);
  router.get('/admin/solicitudes-contacto/:id',admin.solicitudContactoDetalle);
  router.patch('/admin/solicitudes-contacto/:id',admin.actualizarSolicitudContacto);
  router.get('/admin/publicaciones',admin.publicaciones);
  router.get('/admin/publicaciones/:id',admin.publicacionDetalle);
  router.get('/admin/metodos-pago',admin.metodosPago);
  router.get('/admin/cuentas',admin.cuentas);
  router.get('/admin/historial',admin.historial);
  router.post('/admin/solicitudes-publicacion/:id/aprobar',admin.aprobar);
  router.post('/admin/solicitudes-publicacion/:id/rechazar',admin.rechazar);
  router.patch('/admin/cuentas/:id',admin.cuenta);
  router.patch('/admin/publicaciones/:id',admin.actualizar);
  router.post('/admin/publicaciones/:id/cerrar',admin.cerrar);
  return router;
};
